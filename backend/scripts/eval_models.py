"""Evaluation harness — produces real, quotable metrics for MediSense ML models.

Run:  ../venv/bin/python scripts/eval_models.py      (from backend/)
   or: python scripts/eval_models.py                 (in an env with the deps)

What it does:
  • No-show (XGBoost): reproduces the exact held-out test split (random_state=42,
    test_size=0.2, stratified), loads the trained model + scaler + label encoder,
    and prints a FULL classification breakdown — ROC-AUC, PR-AUC, precision,
    recall, F1, accuracy, and the confusion matrix.
  • LSTM anomaly: surfaces the metrics recorded in its training report
    (AUC, F1, Brier, ECE) — reproducible via scripts/train_lstm_anomaly.

Writes a Markdown summary to models/eval_report.md so you have numbers to quote.
"""

from __future__ import annotations

import json
from pathlib import Path

import joblib
import pandas as pd
from sklearn.metrics import (
    average_precision_score,
    confusion_matrix,
    f1_score,
    precision_recall_fscore_support,
    roc_auc_score,
)
from sklearn.model_selection import train_test_split

BACKEND = Path(__file__).resolve().parents[1]
DATA_PATH = BACKEND / "data" / "noshow_synthetic_data.csv"
MODELS = BACKEND / "models"
RANDOM_STATE = 42
TEST_SIZE = 0.2

FEATURE_COLUMNS = [
    "age", "sex", "distance_to_clinic", "weather_score", "previous_noshows",
    "days_since_booking", "day_of_week", "appointment_hour", "chronic_conditions_count",
]


def evaluate_noshow() -> dict:
    df = pd.read_csv(DATA_PATH)
    X = df[FEATURE_COLUMNS].copy()
    y = df["is_noshow"].astype(int)

    # Reproduce the exact training split (same seed / size / stratify)
    _, X_test, _, y_test = train_test_split(
        X, y, test_size=TEST_SIZE, stratify=y, random_state=RANDOM_STATE
    )

    model = joblib.load(MODELS / "noshow_xgb_model.joblib")
    scaler = joblib.load(MODELS / "noshow_scaler.joblib")
    label_encoder = joblib.load(MODELS / "noshow_label_encoder.joblib")

    X_test = X_test.copy()
    X_test["sex"] = label_encoder.transform(X_test["sex"])
    X_test_scaled = scaler.transform(X_test)

    proba = model.predict_proba(X_test_scaled)[:, 1]
    pred = (proba >= 0.5).astype(int)

    roc = roc_auc_score(y_test, proba)
    pr_auc = average_precision_score(y_test, proba)
    f1 = f1_score(y_test, pred)
    prec, rec, _, _ = precision_recall_fscore_support(
        y_test, pred, average="binary", zero_division=0
    )
    acc = (pred == y_test.to_numpy()).mean()
    cm = confusion_matrix(y_test, pred)
    pos_rate = float(y_test.mean())

    print("\n" + "=" * 60)
    print("  NO-SHOW PREDICTION (XGBoost) — held-out test set")
    print("=" * 60)
    print(f"  Test samples         : {len(y_test)}  (positives {pos_rate:.1%})")
    print(f"  ROC-AUC              : {roc:.3f}")
    print(f"  PR-AUC (Avg Prec.)   : {pr_auc:.3f}   <- the right metric for imbalance")
    print(f"  F1                   : {f1:.3f}")
    print(f"  Precision            : {prec:.3f}")
    print(f"  Recall (Sensitivity) : {rec:.3f}")
    print(f"  Accuracy             : {acc:.3f}")
    print("  Confusion matrix      [pred 0, pred 1]")
    print(f"    actual 0 (show)  : {cm[0].tolist()}")
    print(f"    actual 1 (noshow): {cm[1].tolist()}")

    return {
        "model": "XGBoost", "test_samples": int(len(y_test)),
        "positive_rate": round(pos_rate, 4),
        "roc_auc": round(float(roc), 4), "pr_auc": round(float(pr_auc), 4),
        "f1": round(float(f1), 4), "precision": round(float(prec), 4),
        "recall": round(float(rec), 4), "accuracy": round(float(acc), 4),
        "confusion_matrix": cm.tolist(),
    }


def report_lstm() -> dict:
    path = MODELS / "lstm_anomaly_training_report.json"
    if not path.exists():
        print("\n(LSTM report not found — skipping)")
        return {}
    rep = json.loads(path.read_text())
    tm = rep.get("test_metrics", {})
    print("\n" + "=" * 60)
    print("  BIOMETRIC ANOMALY DETECTION (LSTM) — from training report")
    print("=" * 60)
    print(f"  ROC-AUC : {tm.get('auc'):.3f}")
    print(f"  F1      : {tm.get('f1'):.3f}")
    print(f"  Brier   : {tm.get('brier'):.4f}   (calibration; lower = better)")
    print(f"  ECE     : {tm.get('ece'):.4f}   (calibration error; lower = better)")
    cfg = rep.get("config", {})
    print(f"  Arch    : seq_len={cfg.get('seq_len')} feats={cfg.get('n_features')} "
          f"hidden={cfg.get('hidden_dim')} layers={cfg.get('n_layers')}")
    return {"model": "LSTM", **tm, "config": cfg}


def write_markdown(noshow: dict, lstm: dict) -> None:
    cm = noshow.get("confusion_matrix", [[0, 0], [0, 0]])
    md = f"""# MediSense AI — Model Evaluation Report

*Generated by `scripts/eval_models.py`. Numbers are reproducible (no-show uses the
exact stratified test split, random_state=42).*

## No-show prediction — XGBoost (held-out test, {noshow.get('test_samples')} samples)

| Metric | Value |
|---|---|
| ROC-AUC | **{noshow.get('roc_auc')}** |
| PR-AUC (Average Precision) | **{noshow.get('pr_auc')}** |
| F1 | {noshow.get('f1')} |
| Precision | {noshow.get('precision')} |
| Recall (Sensitivity) | {noshow.get('recall')} |
| Accuracy | {noshow.get('accuracy')} |
| Positive (no-show) rate | {noshow.get('positive_rate')} |

Confusion matrix (rows = actual, cols = predicted):

|              | pred show | pred no-show |
|--------------|-----------|--------------|
| actual show   | {cm[0][0]} | {cm[0][1]} |
| actual no-show | {cm[1][0]} | {cm[1][1]} |

> Interview note: I optimize for **PR-AUC / recall**, not accuracy — no-shows are the
> minority class and missing a likely no-show (false negative) is the costly error.

## Biometric anomaly detection — LSTM (from training report)

| Metric | Value |
|---|---|
| ROC-AUC | **{lstm.get('auc')}** |
| F1 | {lstm.get('f1')} |
| Brier score | {lstm.get('brier')} |
| ECE (calibration) | {lstm.get('ece')} |

> The low Brier/ECE mean the model's probabilities are **well-calibrated** — important
> for a medical alerting system where a "0.8 risk" should really mean ~80%.
"""
    out = MODELS / "eval_report.md"
    out.write_text(md)
    print(f"\n✓ wrote {out}")


if __name__ == "__main__":
    ns = evaluate_noshow()
    ls = report_lstm()
    write_markdown(ns, ls)
    print("\nDone.\n")
